"""The verification engine: extraction -> Tier 1 (static) -> optional Tier 2 (semantic) -> score -> persist.

Workflow
1. Load the project's sources, code entities and chunks (existing repositories).
2. Extract claims from the selected Markdown documents (and from code docstrings).
3. Tier 1 verifies every static claim (entities, signatures, parameters, return types) deterministically.
4. Tier 2 runs ONLY for behaviour/config claims, ONLY when requested, and never for a claim Tier 1 already
   decided. Without a usable model those claims are NOT_CHECKABLE and Tier 1 results are unaffected.
5. Documentation coverage findings and the Trust Score are computed.
6. Everything is persisted in ONE transaction (claims, run, results, evidence, findings, score), so a
   failure never leaves partial results. Failed runs are recorded as FAILED with no results.
Old runs are never modified: each call creates a new run.
"""

from __future__ import annotations

import hashlib
from collections import Counter
from typing import Any, Callable, Sequence, Union

from trustdoc.config import Settings
from trustdoc.db import Database
from trustdoc.exceptions import (
    DocumentSelectionError,
    InvalidQuestionError,
    NotFoundError,
    VerificationError,
)
from trustdoc.ingestion.storage import UploadStore
from trustdoc.llm.base import LLMBackend
from trustdoc.logging_setup import get_logger
from trustdoc.models import (
    Chunk,
    Claim,
    ClaimOrigin,
    ClaimResult,
    ClaimType,
    ClaimVerdict,
    CodeEntity,
    EvidenceLink,
    Finding,
    RunStatus,
    Severity,
    Source,
    SourceType,
    TrustScoreBreakdown,
    TrustScoreComponent,
    VerificationRun,
    VerificationTier,
    utcnow,
)
from trustdoc.parsing.python_analyzer import decode_python_source
from trustdoc.verification.extraction import extract_docstring_claims, extract_markdown_claims
from trustdoc.verification.resolver import AliasIndex, EntityResolver
from trustdoc.verification.scoring import ScoreInputs, compute_trust_score
from trustdoc.verification.semantic_verifier import MODEL_PREFIX, SemanticUnavailable, SemanticVerifier
from trustdoc.verification.static_verifier import StaticVerifier, check_documentation_coverage
from trustdoc.verification.types import (
    SEMANTIC_CATEGORIES,
    STATIC_CATEGORIES,
    UID,
    ClaimOutcome,
    ClaimReport,
    EvidenceRef,
    FindingReport,
    ScoreReport,
    VerificationReport,
    claim_uid,
)

log = get_logger("verification")
ENGINE_VERSION = "5.0"
MAX_CONSECUTIVE_MODEL_FAILURES = 3
LLMSource = Union[LLMBackend, Callable[[], LLMBackend], None]


class VerificationEngine:
    def __init__(self, db: Database, settings: Settings, *, retriever=None, llm: LLMSource = None, ingestion=None) -> None:
        self._db = db
        self._settings = settings
        self._retriever = retriever
        self._llm = llm
        self._ingestion = ingestion
        self._store = UploadStore(settings.storage.uploads_dir)

    # ------------------------------------------------------------------------ public API
    def verify_project(
        self,
        project_id: int,
        *,
        documents: Sequence[str] | None = None,
        include_docstrings: bool = True,
        semantic: bool = False,
    ) -> VerificationReport:
        """Verify a project's Markdown documentation (all of it, or the named sources) and docstrings."""
        return self._run(project_id, documents=documents, include_docstrings=include_docstrings, include_coverage=True,
                         semantic=semantic, origin=ClaimOrigin.EXISTING_DOC)

    def verify_text(self, project_id: int, text: str, *, name: str | None = None, semantic: bool = False) -> VerificationReport:
        """Verify documentation supplied as text (e.g. generated by Part 4) against the project's code.

        The text is stored as a Markdown source of the project (so claims keep full provenance); claims are
        marked as GENERATED. Docstring checks and project-wide coverage are not part of such a run.
        """
        if not text or not text.strip():
            raise DocumentSelectionError("The supplied documentation text is empty.")
        if self._ingestion is None:
            from trustdoc.ingestion import IngestionService

            self._ingestion = IngestionService(self._db, self._settings)
        name = name or f"generated/verify-{hashlib.sha256(text.encode('utf-8')).hexdigest()[:10]}.md"
        self._ingestion.ingest_bytes(project_id, name, text.encode("utf-8"), source_type=SourceType.MARKDOWN)
        return self._run(project_id, documents=[name], include_docstrings=False, include_coverage=False, semantic=semantic,
                         origin=ClaimOrigin.GENERATED)

    def list_runs(self, project_id: int) -> list[VerificationRun]:
        with self._db.session() as s:
            s.projects.require(project_id)
            return s.runs.list_for_project(project_id)

    def load_report(self, run_id: int) -> VerificationReport:
        """Rebuild the full report of a stored run (historical runs stay accessible and unchanged)."""
        with self._db.session() as s:
            run = s.runs.require(run_id)
            results = s.findings.list_claim_results(run_id)
            finding_rows = s.findings.list_for_run(run_id)
            claims = {r.claim_id: s.claims.get(r.claim_id) for r in results}
            chunk_ids = list({e.chunk_id for r in results for e in r.evidence})
            chunks = {c.id: c for c in s.chunks.get_many(chunk_ids)}
            source_names: dict[int, str] = {}
            for c in chunks.values():
                if c.source_id not in source_names:
                    src = s.sources.get(c.source_id)
                    source_names[c.source_id] = src.name if src else "(source removed)"
            breakdown = s.runs.get_trust_breakdown(run_id)

        by_claim: dict[int, list[str]] = {}
        findings: list[FindingReport] = []
        for f in finding_rows:
            d = f.details or {}
            uid = d.get("finding_uid", f"f{f.id}")
            if f.claim_id is not None:
                by_claim.setdefault(f.claim_id, []).append(uid)
            findings.append(FindingReport(
                uid=uid, claim_uid=d.get("claim_uid"), category=d.get("category", "other"), status=d.get("status", ""), severity=f.severity,
                issue_type=f.issue_type.value, message=f.message, suggestion=f.suggestion, tier=f.tier, doc_location=d.get("doc_location"),
                code_location=d.get("code_location"), evidence=d.get("evidence", []), model_assisted=bool(d.get("model_assisted")),
                claim_text=d.get("claim_text"), detail=d.get("detail", {})))
        findings.sort(key=lambda f: (-f.severity.rank, f.uid))

        claim_reports: list[ClaimReport] = []
        for r in results:
            c = claims.get(r.claim_id)
            if c is None:
                continue
            refs = []
            for e in r.evidence:
                chunk = chunks.get(e.chunk_id)
                label = chunk.location_label(source_names[chunk.source_id]) if chunk else "(chunk no longer available)"
                refs.append(EvidenceRef(e.chunk_id, label, e.stance.value, e.relevance_score))
            claim_reports.append(ClaimReport(
                claim_id=c.id, claim_uid=claim_uid(c), text=c.text, category=c.claim_type, status=r.verdict, tier=r.tier,
                explanation=r.rationale, origin=c.origin.value, doc_label=c.extracted.get("doc_label") or f"line {c.start_line}",
                subject=c.subject_name, confidence=r.confidence, model_assisted=r.rationale.startswith(MODEL_PREFIX),
                evidence=refs, finding_uids=by_claim.get(c.id, [])))

        summary = run.summary or {}
        score = None
        if summary.get("score"):
            sc = summary["score"]
            comps = breakdown.components if breakdown else [TrustScoreComponent(**c) for c in sc.get("components", [])]
            score = ScoreReport(final=run.trust_score, base=sc.get("base"), components=comps, penalties=sc.get("penalties", []),
                                inputs=sc.get("inputs", {}), notes=sc.get("notes", []))
        warnings = list(summary.get("warnings", []))
        if run.status == RunStatus.FAILED and run.error_message:
            warnings.insert(0, f"Run failed: {run.error_message}")
        return VerificationReport(run=run, project_id=run.project_id, documents=summary.get("documents", []), counts=summary.get("counts", {}),
                                  claims=claim_reports, findings=findings, score=score, skipped=list(summary.get("skipped", [])),
                                  warnings=warnings, semantic=summary.get("semantic", {}))

    # ------------------------------------------------------------------------------ run
    def _run(self, project_id: int, *, documents, include_docstrings: bool, include_coverage: bool, semantic: bool,
             origin: ClaimOrigin) -> VerificationReport:
        if documents is not None:
            # The same document named more than once would be extracted twice and yield duplicate claims (and thus
            # duplicate (run_id, claim_id) results). De-duplicate, keeping the order of first appearance.
            documents = list(dict.fromkeys(documents))
        snapshot = self._config_snapshot(documents, include_docstrings, include_coverage, semantic)
        try:
            computed = self._compute(project_id, documents, include_docstrings, include_coverage, semantic, origin)
            run_id = self._persist(project_id, snapshot, computed)
        except (NotFoundError, DocumentSelectionError, InvalidQuestionError):
            raise                                              # bad input: nothing was computed, no run is recorded
        except Exception as exc:  # noqa: BLE001
            log.exception("Verification failed for project %d", project_id)
            self._record_failure(project_id, snapshot, exc)
            raise VerificationError(f"Verification failed: {type(exc).__name__}: {exc}") from exc
        log.info("Verification run %d finished for project %d: %s", run_id, project_id, computed["counts"])
        return self.load_report(run_id)

    def _config_snapshot(self, documents, include_docstrings, include_coverage, semantic) -> dict[str, Any]:
        v = self._settings.verification
        snap: dict[str, Any] = {
            "engine_version": ENGINE_VERSION, "documents": list(documents) if documents else "all markdown",
            "include_docstrings": include_docstrings, "include_coverage": include_coverage, "semantic_requested": semantic,
            "weights": {"accuracy": v.weight_accuracy, "coverage": v.weight_coverage, "grounding": v.weight_grounding},
            "penalties": {"critical": v.penalty_critical, "high": v.penalty_high, "cap": v.penalty_cap},
        }
        if semantic:
            snap["semantic"] = {"evidence_top_k": v.evidence_top_k, "evidence_types": list(v.evidence_source_types),
                                "max_claims": v.max_semantic_claims, "llm_provider": self._settings.llm.provider, "llm_model": self._settings.llm.model}
        return snap

    # --------------------------------------------------------------------------- compute
    def _compute(self, project_id, documents, include_docstrings, include_coverage, semantic, origin) -> dict[str, Any]:
        with self._db.session() as s:
            s.projects.require(project_id)
            sources = s.sources.list_for_project(project_id)
            entities = s.entities.list_for_project(project_id)
            chunks = s.chunks.list_for_project(project_id)
        source_names = {x.id: x.name for x in sources}
        id_by_name = {x.name: x.id for x in sources}
        warnings: list[str] = []

        doc_sources = self._select_documents(sources, documents)
        claims: list[Claim] = []
        mentions: set[str] = set()
        read_docs: list[str] = []
        for src in doc_sources:
            try:
                text = self._store.read(src.stored_path).decode("utf-8-sig")
            except (OSError, UnicodeDecodeError, TypeError) as exc:
                warnings.append(f"{src.name}: could not be read from storage ({type(exc).__name__}); skipped")
                continue
            extraction = extract_markdown_claims(text, src.name, origin=origin)
            claims += extraction.claims
            mentions |= extraction.mentions
            warnings += extraction.warnings
            read_docs.append(src.name)
        if include_docstrings:
            extraction = extract_docstring_claims(entities, source_names, origin=origin)
            claims += extraction.claims
            warnings += extraction.warnings

        entity_chunks: dict[int, list[int]] = {}
        chunks_by_source: dict[int, list[Chunk]] = {}
        for ch in chunks:
            chunks_by_source.setdefault(ch.source_id, []).append(ch)
            if ch.entity_id is not None:
                entity_chunks.setdefault(ch.entity_id, []).append(ch.id)
        entity_by_qname: dict[str, CodeEntity] = {}
        for e in entities:
            entity_by_qname.setdefault(e.qualified_name, e)
        for c in claims:                                       # stamp ids and link each claim to the chunk it came from
            c.project_id = project_id
            c.source_id = id_by_name[c.extracted["doc_source_name"]]
            if c.extracted.get("context") == "docstring":
                ent = entity_by_qname.get(c.subject_name or "")
                ids = entity_chunks.get(ent.id, []) if ent else []
                c.chunk_id = ids[0] if ids else None
            else:
                c.chunk_id = next((ch.id for ch in chunks_by_source.get(c.source_id, [])
                                   if ch.start_line is not None and ch.end_line is not None and c.start_line is not None
                                   and ch.start_line <= c.start_line <= ch.end_line), None)

        alias_texts = []
        for src in sources:
            if src.source_type == SourceType.PYTHON:
                try:
                    alias_texts.append(decode_python_source(self._store.read(src.stored_path), src.name)[0])
                except Exception:  # noqa: BLE001 - alias detection is best-effort
                    continue
        resolver = EntityResolver(entities, AliasIndex.from_sources(alias_texts))
        static = StaticVerifier(resolver, source_names, entity_chunks)

        outcomes: list[ClaimOutcome] = []
        semantic_claims: list[Claim] = []
        for c in claims:
            if c.claim_type in STATIC_CATEGORIES:
                outcomes.append(static.verify(c))
            else:
                semantic_claims.append(c)
        sem_info = self._run_semantic(project_id, semantic_claims, semantic, outcomes)

        coverage_findings: list[Finding] = []
        coverage_stats = {"public_entities": 0, "documented_entities": 0}
        if include_coverage:
            coverage_findings, coverage_stats = check_documentation_coverage(entities, resolver, mentions, source_names)

        if not entities:
            warnings.append("The project has no indexed Python entities; code-based checks and coverage are unavailable.")
        if not doc_sources and not include_docstrings:
            warnings.append("No documentation was selected for verification.")
        counts, score = self._score(outcomes, coverage_findings, coverage_stats, claims)
        skipped = _skipped_messages(outcomes, sem_info, self._settings.verification.max_semantic_claims)
        return {"claims": claims, "outcomes": outcomes, "coverage_findings": coverage_findings, "score": score, "counts": counts,
                "documents": read_docs, "warnings": warnings, "skipped": skipped, "semantic": sem_info}

    def _select_documents(self, sources: Sequence[Source], documents: Sequence[str] | None) -> list[Source]:
        if documents is None:
            return [x for x in sources if x.source_type == SourceType.MARKDOWN]
        by_name = {x.name: x for x in sources}
        chosen: list[Source] = []
        for name in documents:
            src = by_name.get(name)
            if src is None:
                raise DocumentSelectionError(f"No source named {name!r} in this project. Known documents: "
                                             f"{', '.join(x.name for x in sources if x.source_type == SourceType.MARKDOWN) or '(none)'}")
            if src.source_type != SourceType.MARKDOWN:
                raise DocumentSelectionError(f"{name!r} is a {src.source_type.value} source; only Markdown documentation can be verified "
                                             "(Python docstrings are checked automatically).")
            chosen.append(src)
        return chosen

    # -------------------------------------------------------------------- semantic tier
    def _run_semantic(self, project_id: int, claims: list[Claim], requested: bool, outcomes: list[ClaimOutcome]) -> dict[str, Any]:
        info: dict[str, Any] = {"requested": requested, "claims": len(claims), "checked": 0, "model": None, "unavailable_reason": None}
        if not claims:
            return info

        def skip(c: Claim, key: str, message: str) -> None:
            outcomes.append(ClaimOutcome(c, VerificationTier.SEMANTIC, ClaimVerdict.NOT_CHECKABLE, message, skip_reason=key))

        if not requested:
            for c in claims:
                skip(c, "semantic_disabled", "Semantic verification was not requested for this run.")
            return info
        try:
            if self._retriever is None:
                try:
                    from trustdoc.retrieval.factory import create_retriever
                except ImportError as exc:
                    raise SemanticUnavailable(f"retrieval dependencies are not installed ({exc}); install them with: pip install -e \".[retrieval]\"",
                                              "dependency_missing") from exc
                self._retriever = create_retriever(self._db, self._settings)
            verifier = SemanticVerifier(self._settings, self._retriever, self._llm)
            verifier.prepare()
            info["model"] = verifier.model_description
        except SemanticUnavailable as exc:
            info["unavailable_reason"] = exc.reason
            for c in claims:
                skip(c, exc.kind, exc.reason)
            return info

        limit, failures = self._settings.verification.max_semantic_claims, 0
        for index, c in enumerate(claims):
            if index >= limit:
                skip(c, "limit", f"Not checked: the per-run semantic claim limit ({limit}) was reached.")
                continue
            if info["unavailable_reason"]:
                skip(c, "llm_unavailable", info["unavailable_reason"])
                continue
            try:
                outcome = verifier.verify(project_id, c)
            except SemanticUnavailable as exc:
                info["unavailable_reason"] = exc.reason
                skip(c, exc.kind, exc.reason)
                continue
            failures = failures + 1 if outcome.skip_reason == "llm_error" else 0
            if failures >= MAX_CONSECUTIVE_MODEL_FAILURES:
                info["unavailable_reason"] = f"the model failed {failures} times in a row; semantic checking was stopped"
            if outcome.skip_reason != "llm_error":
                info["checked"] += 1
            outcomes.append(outcome)
        return info

    # --------------------------------------------------------------------------- scoring
    def _score(self, outcomes: list[ClaimOutcome], coverage_findings: list[Finding], stats: dict[str, int], claims: list[Claim]):
        verdicts = Counter(o.verdict for o in outcomes)
        all_findings = [f for o in outcomes for f in o.findings] + coverage_findings
        by_sev = Counter(f.severity for f in all_findings)
        contradictions = [f for o in outcomes for f in o.findings if (f.details or {}).get("status") == ClaimVerdict.CONTRADICTED.value]
        grounded = sum(1 for o in outcomes if o.verdict in (ClaimVerdict.SUPPORTED, ClaimVerdict.CONTRADICTED) and o.evidence)
        inputs = ScoreInputs(
            supported=verdicts[ClaimVerdict.SUPPORTED], contradicted=verdicts[ClaimVerdict.CONTRADICTED],
            insufficient=verdicts[ClaimVerdict.INSUFFICIENT_EVIDENCE], not_checkable=verdicts[ClaimVerdict.NOT_CHECKABLE], grounded=grounded,
            public_entities=stats["public_entities"], documented_entities=stats["documented_entities"],
            critical_contradictions=sum(1 for f in contradictions if f.severity == Severity.CRITICAL),
            high_contradictions=sum(1 for f in contradictions if f.severity == Severity.HIGH))
        counts = {
            "claims": len(claims), "supported": inputs.supported, "contradicted": inputs.contradicted,
            "insufficient_evidence": inputs.insufficient, "not_checkable": inputs.not_checkable, "findings": len(all_findings),
            **{f"findings_{s.value}": by_sev[s] for s in Severity}, **stats,
            "static_claims": sum(1 for c in claims if c.claim_type in STATIC_CATEGORIES),
            "semantic_claims": sum(1 for c in claims if c.claim_type in SEMANTIC_CATEGORIES),
        }
        return counts, compute_trust_score(inputs, self._settings.verification)

    # ------------------------------------------------------------------------ persistence
    def _persist(self, project_id: int, snapshot: dict[str, Any], computed: dict[str, Any]) -> int:
        """Write the whole run in ONE transaction; any exception rolls everything back."""
        claims: list[Claim] = computed["claims"]
        outcomes: list[ClaimOutcome] = computed["outcomes"]
        score: ScoreReport = computed["score"]
        summary = {
            "counts": computed["counts"], "documents": computed["documents"], "skipped": computed["skipped"],
            "warnings": computed["warnings"], "semantic": computed["semantic"], "score": score.to_dict(),
            "by_category": dict(Counter(c.claim_type.value for c in claims)),
        }
        with self._db.session() as s:
            run = s.runs.create(VerificationRun(project_id, status=RunStatus.RUNNING, config_snapshot=snapshot, started_at=utcnow()))
            existing: dict[int, dict[str, Claim]] = {}
            for c in claims:                                    # reuse identical claims from earlier runs
                known = existing.setdefault(c.source_id, {claim_uid(x): x for x in s.claims.list_for_source(c.source_id) if claim_uid(x)})
                prior = known.get(claim_uid(c))
                if prior is not None:
                    c.id = prior.id
                else:
                    s.claims.add(c)
                    known[claim_uid(c)] = c
            for o in outcomes:
                result = ClaimResult(
                    run_id=run.id, claim_id=o.claim.id, tier=o.tier, verdict=o.verdict, confidence=o.confidence, rationale=o.rationale[:2000],
                    evidence=[EvidenceLink(chunk_id=d.chunk_id, stance=d.stance, relevance_score=d.relevance_score, rank=d.rank) for d in o.evidence])
                s.findings.add_claim_result(result)
                for f in o.findings:
                    f.run_id, f.project_id, f.claim_id = run.id, project_id, o.claim.id
                    s.findings.add(f)
            for f in computed["coverage_findings"]:
                f.run_id, f.project_id = run.id, project_id
                s.findings.add(f)
            if score.final is not None:
                s.runs.save_trust_breakdown(run.id, TrustScoreBreakdown(score.components, score.final))
            s.runs.complete(run.id, summary=summary)
            return run.id

    def _record_failure(self, project_id: int, snapshot: dict[str, Any], exc: BaseException) -> None:
        try:
            with self._db.session() as s:
                run = s.runs.create(VerificationRun(project_id, status=RunStatus.PENDING, config_snapshot=snapshot))
                s.runs.fail(run.id, f"{type(exc).__name__}: {exc}"[:1000])
        except Exception:  # noqa: BLE001
            log.exception("Could not record the failed verification run")


def _skipped_messages(outcomes: list[ClaimOutcome], sem: dict[str, Any], limit: int) -> list[str]:
    counts = Counter(o.skip_reason for o in outcomes if o.verdict == ClaimVerdict.NOT_CHECKABLE and o.skip_reason)
    out: list[str] = []
    if counts.get("semantic_disabled"):
        out.append(f"Semantic verification was not run (enable it with --semantic and a configured local LLM): {counts['semantic_disabled']} "
                   "behaviour/config claim(s) were not checked.")
    reasons = {o.rationale for o in outcomes if o.skip_reason in ("not_configured", "dependency_missing", "llm_unavailable", "retrieval_unavailable", "unavailable")}
    n_unavail = sum(counts.get(k, 0) for k in ("not_configured", "dependency_missing", "llm_unavailable", "retrieval_unavailable", "unavailable"))
    if n_unavail:
        out.append(f"Semantic verification was unavailable ({'; '.join(sorted(reasons))[:300]}): {n_unavail} claim(s) were not checked.")
    if counts.get("limit"):
        out.append(f"{counts['limit']} claim(s) exceeded the semantic claim limit ({limit}) and were not checked (TRUSTDOC_VERIFY_MAX_SEMANTIC_CLAIMS).")
    if counts.get("llm_error"):
        out.append(f"{counts['llm_error']} claim(s) were skipped because the model returned an error.")
    if counts.get("external"):
        out.append(f"{counts['external']} claim(s) refer to builtin, standard-library or external names and were not checked.")
    if counts.get("example_code"):
        out.append(f"{counts['example_code']} claim(s) come from example code, which may define its own functions, and were not checked.")
    if counts.get("invalid"):
        out.append(f"{counts['invalid']} claim(s) did not reference a valid Python name and were not checked.")
    return out
